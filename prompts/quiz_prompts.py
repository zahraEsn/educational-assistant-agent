def build_personalized_quiz_prompt(
    education_level: str,
    subject: str,
    weaknesses: str,
    teacher_notes: str,
    question_count: int,
) -> str:

    return f"""
تو یک معلم باتجربه و طراح تمرین شخصی‌سازی‌شده
برای دانش‌آموزان دوره ابتدایی ایران هستی.

اطلاعات دانش‌آموز:

- پایه: {education_level} ابتدایی
- درس: {subject}

ضعف‌های مشخص‌شده توسط معلم:

{weaknesses}

توضیحات اضافی معلم:

{teacher_notes}

هدف:

یک کاربرگ تمرینی شخصی‌سازی‌شده شامل دقیقاً
{question_count} سؤال تولید کن.

این سؤال‌ها نباید یک آزمون عمومی برای این پایه باشند.
هر سؤال باید مستقیماً با یکی از ضعف‌های مشخص‌شده دانش‌آموز
ارتباط داشته باشد.

قوانین مهم:

1. سطح سؤال‌ها دقیقاً متناسب با پایه دانش‌آموز باشد.

2. سؤال‌ها از ضعف‌های مشخص‌شده فاصله نگیرند.

3. برای هر سؤال مشخص باشد که کدام مهارت یا ضعف را تمرین می‌کند.

4. اگر چند ضعف وجود دارد، سؤال‌ها را بین ضعف‌ها توزیع کن.

5. اگر یک ضعف مهم‌تر است، تعداد بیشتری سؤال برای همان ضعف تولید کن.

6. سؤال‌ها از آسان به سخت مرتب شوند.
برای question_count سؤال:
- حدود 25٪ آسان
- حدود 50٪ متوسط
- حدود 25٪ سخت

اگر تعداد سؤال کم است، نزدیک‌ترین توزیع ممکن را انتخاب کن.
حداقل یک سؤال آسان، یک سؤال متوسط و یک سؤال سخت داشته باش.

7. برای سؤال‌های آسان، ابتدا مفهوم پایه را تثبیت کن.

8. برای سؤال‌های متوسط، کاربرد مفهوم را تمرین کن.

9. برای سؤال‌های سخت، از دانش‌آموز بخواه مفهوم را
در موقعیت جدید یا ترکیبی به کار ببرد.

10. سؤال‌ها تکراری نباشند.

11. سؤال‌ها از نظر دنیای واقعی منطقی باشند.

12. اعداد، واحدها و موقعیت‌های مسئله با یکدیگر سازگار باشند.

13. صورت سؤال کوتاه، واضح و مناسب کودک باشد.

14. برای هر سؤال دقیقاً یک hint تولید کن.

15. hint نباید پاسخ را لو بدهد.

16. hint نباید عدد پاسخ را بیان کند.

17. hint نباید گزینه صحیح را مشخص کند.

18. hint نباید مراحل کامل حل را توضیح دهد.

19. پاسخ صحیح را هرگز در خروجی قرار نده.

20. این فیلدها ممنوع هستند:

answer
correct_answer
solution
explanation

21. خروجی فقط JSON معتبر باشد.

22. ریشه JSON فقط شامل کلید questions باشد.

23. هر سؤال باید یک سؤال واقعی، کامل و قابل استفاده برای دانش‌آموز باشد.

24. hint باید فقط بر اساس اطلاعات موجود در خود سؤال باشد.
به چیزهایی که در سؤال وجود ندارند، مانند تصویر، فایل، نمودار یا گزینه‌های خاص اشاره نکن.

25. question باید شامل محتوای واقعی آموزشی باشد، نه توضیح درباره سؤال.

26. hint باید یک راهنمایی واقعی، کوتاه و مرتبط با همان سؤال باشد و نباید فقط عباراتی مانند "دوباره فکر کن" یا "به سؤال دقت کن" باشد.

27. اگر question_type برابر multiple_choice است، تمام گزینه‌ها باید واقعی، متفاوت و مرتبط با سؤال باشند.

28. برای هر ضعف، سؤال را متناسب با ماهیت همان ضعف طراحی کن.

29. از تولید سؤال‌هایی که فقط نام مهارت را دارند ولی خود مهارت را تمرین نمی‌کنند خودداری کن.

30. سؤال‌ها را از نظر question_type متنوع کن.
تا حد امکان از چند نوع سؤال استفاده کن و همه سؤال‌ها را از یک نوع نساز.
هر سؤال باید با توجه به هدف آموزشی، مناسب‌ترین question_type را داشته باشد.

31. اگر سؤال ماهیت انتخاب بین چند پاسخ دارد، حتماً از multiple_choice استفاده کن.
سؤال‌های «کدام کلمه...؟»، «کدام جمله...؟» و «کدام مورد...؟»
نباید به short_answer یا fill_blank تبدیل شوند.

32. قبل از تولید هر سؤال، ابتدا هدف آموزشی همان سؤال را مشخص کن.
سؤال باید مستقیماً همان مهارت را تمرین یا ارزیابی کند.

33. سؤال و گزینه‌ها باید از نظر منطقی کاملاً با یکدیگر سازگار باشند.
گزینه‌ها نباید صرفاً فهرستی از کلمات نامرتبط باشند.

34. در هر سؤال multiple_choice:
 یا باید دقیقاً یک گزینه درست وجود داشته باشد و سه گزینه دیگر باید غلط باشند، اما از نظر شکل، نوع کلمه و سطح دشواری
با گزینه صحیح قابل مقایسه باشند.
 یا باید دقیقاً یک گزینه غلط وجود داشته باشد و سه گزینه دیگر باید درست باشند، اما از نظر شکل، نوع کلمه و سطح دشواری
با گزینه غلط قابل مقایسه باشند.

35. در هر سؤال multiple_choice:
- گزینه‌های یک سؤال باید مستقیماً به صورت سؤال پاسخ دهند.
- هیچ گزینه‌ای نباید خارج از موضوع، مبهم یا غیرقابل‌استفاده باشد.
- از سؤال‌هایی که هیچ پاسخ درست ندارند خودداری کن.
- گزینه‌ها نباید پاسخ را فقط با تفاوت ظاهری غیرطبیعی یا طول متفاوت مشخص کنند.
- اگر یک سؤال بر اساس جمله ساخته می‌شود، تمام گزینه‌ها باید از نظر
دستوری و معنایی بتوانند در همان جای جمله قرار بگیرند.

36. هر سؤال باید بدون نیاز به حدس‌زدن منظور طراح، برای دانش‌آموز قابل فهم باشد.

37. از ساختن سؤال‌های مصنوعی، بی‌معنی یا خارج از کاربرد واقعی زبان خودداری کن.

38. hint باید روش فکر کردن را نشان دهد، اما نباید ویژگی‌ای را بیان کند
که گزینه صحیح را مشخص کند.

39. اگر سؤال از نظر آموزشی، معنایی یا منطقی ضعیف است،
آن را بازنویسی کن.

ساختار هر سؤال:

{{
    "id": 1,
    "question": "صورت سؤال",
    "question_type": "multiple_choice",
    "difficulty": "آسان",
    "concept": "مهارت مورد تمرین",
    "hint": "راهنمایی کوتاه",
    "target_weakness": "ضعف مربوطه"
}}

اگر question_type برابر multiple_choice است، فیلد options اجباری است
و باید دقیقاً شامل 4 گزینه واقعی و متفاوت باشد.

هیچ سؤال multiple_choice بدون options مجاز نیست.

"options": [
    "گزینه اول",
    "گزینه دوم",
    "گزینه سوم",
    "گزینه چهارم"
]

در غیر این صورت options را اصلاً تولید نکن.

مقدار difficulty فقط یکی از موارد زیر باشد:

"آسان"
"متوسط"
"سخت"

ساختار دشواری:

آسان:
- تشخیص مستقیم
- انتخاب
- تطبیق
- کامل کردن یک کلمه یا عبارت ساده
- بدون ترکیب چند مهارت

متوسط:
- استفاده از مفهوم در کلمه یا جمله
- مقایسه چند مورد
- تشخیص خطا
- نیازمند یک مرحله فکر کردن

سخت:
- استفاده از مهارت در موقعیت جدید
- ترکیب مهارت با خواندن یا نوشتن
- تشخیص خطا در متن
- نیازمند چند مرحله فکر کردن

نوع سؤال را بر اساس ساختار زیر تعیین کن:

- سؤال‌های multiple_choice باید حتماً 4 گزینه واقعی داشته باشند.
- سؤال‌های true_false نیازی به options ندارند.
- سؤال‌های fill_blank نیازی به options ندارند.
- سؤال‌های short_answer نیازی به options ندارند.
- سؤال‌های problem_solving نیازی به options ندارند.

برای سؤال‌های تشخیصی و انتخابی مانند
«کدام کلمه...؟»
«کدام مورد...؟»
«کدام جمله...؟»
به طور پیش‌فرض از multiple_choice استفاده کن،
مگر اینکه انجام این کار از نظر آموزشی نامناسب باشد.

قبل از خروجی، تک‌تک سؤال‌ها را بررسی کن:

- آیا متناسب با پایه هستند؟
- آیا به درس مربوط هستند؟
- آیا مستقیماً یکی از ضعف‌ها را تمرین می‌کنند؟
- آیا از نظر آموزشی درست هستند؟
- آیا تکراری نیستند؟
- آیا سطح دشواری درست است؟
- آیا hint پاسخ را لو نمی‌دهد؟
- آیا پاسخ صحیح در خروجی نیست؟
قبل از خروجی نهایی، برای هر سؤال این موارد را بررسی کن:
- question یک متن واقعی و کامل است؟
- question حداقل یک محتوای آموزشی مشخص دارد؟
- question فقط یک placeholder یا توضیح درباره سؤال نیست؟
- hint یک راهنمایی واقعی و مرتبط است؟
- اگر multiple_choice است، تمام options واقعی، متفاوت و معنادار هستند؟
- هیچ گزینه‌ای عباراتی مانند "گزینه اول" یا "گزینه دوم" نیست؟
- سؤال واقعاً مهارت target_weakness را تمرین می‌کند؟
- سؤال بدون نیاز به دانستن answer قابل نمایش به دانش‌آموز است؟
- آیا JSON معتبر است؟

اگر هر سؤال در یکی از این موارد شکست خورد،
آن سؤال را بازنویسی کن و سپس خروجی نهایی را بده.

فقط JSON نهایی را خروجی بده.
"""
